function normalizeAutoText(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[؟?!！。，,؛;:]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function getAutomaticReply(text) {
  const value = normalizeAutoText(text);

  if (!value || value.startsWith(".") || value.startsWith("/")) {
    return null;
  }

  for (const group of AUTO_REPLY_GROUPS) {
    const matched = group.triggers.some(trigger => {
      const t = normalizeAutoText(trigger);
      return value === t;
    });

    if (matched && group.replies?.length) {
      return group.replies[
        Math.floor(Math.random() * group.replies.length)
      ];
    }
  }

  return null;
}

module.exports = {
  AUTO_REPLY_GROUPS,
  getAutomaticReply,
  normalizeAutoText
};
